from quicksort import quicksort

arrayInt = [8, 2, 4, 7, 1, 3, 9, 6, 5]

# Facciamo una print iniziale dell'array per vedere come è prima di iniziare l'ordinamento
print("Array iniziale: ", arrayInt)

# Ora chiamiamo la funzione quicksort e stampiamo l'array ordinato
print("Array ordinato: ", quicksort(arrayInt))
